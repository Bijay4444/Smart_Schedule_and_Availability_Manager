"""Copy configured integration settings to the VM's private .env over pinned SSH.

Default: report presence only. --apply backs up and updates just integration keys.
No values are printed, placed in command arguments, committed, or sent to GitHub.
This stages settings for the next CI/CD release; it does not restart containers.
"""
import argparse
import json
import os
from pathlib import Path
import shlex
import subprocess

KEYS = ('GROQ_API_KEY', 'GROQ_MODEL', 'GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET',
        'GITHUB_CLIENT_ID', 'GITHUB_CLIENT_SECRET')


def quote_value(value):
    # Compose treats single-quoted values literally, including $ characters.
    # Credentials generated by these providers need no embedded quotes/backslashes.
    if not isinstance(value, str) or any(c in value for c in "'\\\n\r\0"):
        raise ValueError('Integration value requires manual dotenv quoting; no values were updated.')
    return "'" + value + "'"


def update_text(original, values):
    if not set(values) <= set(KEYS):
        raise ValueError('Only integration settings may be updated.')
    lines = original.splitlines()
    for key, value in values.items():
        encoded = quote_value(value)
        matches = [i for i, line in enumerate(lines) if line.strip().startswith(key + '=') or line.strip().startswith('export ' + key + '=')]
        if len(matches) > 1:
            raise ValueError('Duplicate integration key; resolve the environment file before updating.')
        line = key + '=' + encoded
        if matches:
            lines[matches[0]] = line
        else:
            lines.append(line)
    return '\n'.join(lines) + '\n'


# Embed only the pure, allowlisted updater. Secrets enter via encrypted SSH stdin.
REMOTE = '''
import fcntl, json, os, shutil, tempfile
from datetime import UTC, datetime
from pathlib import Path
KEYS = {keys!r}
{quote_source}
{update_source}
payload = json.load(__import__('sys').stdin)
values = payload['values']
path = Path('/opt/smart-schedule/.env')
if not path.is_file() or path.is_symlink():
    raise ValueError('Expected the existing private VM environment file')
with (path.parent / '.ci-deploy.lock').open('a') as lock:
    os.fchmod(lock.fileno(), 0o600)
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    if (path.parent / '.deploy-lock').exists():
        raise ValueError('A deployment is running; retry after it completes')
    old = path.read_text()
    present = {{key: any(line.strip().startswith(key + '=') and bool(line.split('=',1)[1].strip().strip("\\\"'")) for line in old.splitlines()) for key in KEYS}}
    if payload['apply']:
        updated = update_text(old, values)
        if updated != old:
            backup = path.parent / ('integration-env-' + datetime.now(UTC).strftime('%Y%m%dT%H%M%S%f') + '.bak')
            shutil.copyfile(path, backup)
            backup.chmod(0o600)
            stat = path.stat()
            with tempfile.NamedTemporaryFile(mode='w', dir=path.parent, delete=False) as stream:
                temporary = Path(stream.name)
                os.fchmod(stream.fileno(), 0o600)
                os.fchown(stream.fileno(), stat.st_uid, stat.st_gid)
                stream.write(updated)
            temporary.replace(path)
        present.update({{key: bool(value) for key,value in values.items()}})
    print(json.dumps({{'applied': payload['apply'], 'configured': present,
                      'containersRestarted': False, 'valuesPrinted': False}}))
'''


def remote_program():
    import inspect
    return REMOTE.format(keys=KEYS, quote_source=inspect.getsource(quote_value), update_source=inspect.getsource(update_text))


def main():
    import environ
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--env-file', type=Path, default=Path('.env'))
    parser.add_argument('--host', required=True)
    parser.add_argument('--user', default='azureuser')
    parser.add_argument('--identity', type=Path, default=Path('.azure-deploy/vm/id_rsa'))
    parser.add_argument('--known-hosts', type=Path, default=Path('.azure-deploy/vm/known_hosts'))
    parser.add_argument('--apply', action='store_true')
    args = parser.parse_args()
    if not args.env_file.is_file():
        parser.error('Local environment file is missing.')
    # Parse as data, never source the file into a shell. Do not inherit unrelated local settings.
    for key in KEYS:
        os.environ.pop(key, None)
    environ.Env.read_env(args.env_file, overwrite=True)
    values = {key: os.environ[key] for key in KEYS if os.environ.get(key)}
    if not values:
        parser.error('No local integration values are configured.')
    for prefix in ('GOOGLE', 'GITHUB'):
        if (prefix + '_CLIENT_ID' in values) != (prefix + '_CLIENT_SECRET' in values):
            parser.error(prefix + ' requires both client ID and secret.')
    try:
        for value in values.values():
            quote_value(value)
    except ValueError as error:
        parser.error(str(error))
    if args.host.startswith('-') or args.user.startswith('-') or any(c in args.host + args.user for c in ' \r\n\t'):
        parser.error('Invalid SSH target.')
    command = ['ssh', '-i', str(args.identity), '-o', 'BatchMode=yes',
               '-o', 'StrictHostKeyChecking=yes', '-o', 'UserKnownHostsFile=' + str(args.known_hosts),
               '-o', 'ConnectTimeout=15', args.user + '@' + args.host,
               'sudo python3 -c ' + shlex.quote(remote_program())]
    # Strip integration secrets from the SSH process environment; send only via stdin.
    clean_environment = {key: value for key, value in os.environ.items() if key not in KEYS}
    result = subprocess.run(command, input=json.dumps({'apply': args.apply, 'values': values}),
                            text=True, capture_output=True, env=clean_environment)
    if result.returncode:
        parser.exit(1, 'VM environment update failed (SSH/access or remote validation). No secret output was printed.\n')
    report = json.loads(result.stdout)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
